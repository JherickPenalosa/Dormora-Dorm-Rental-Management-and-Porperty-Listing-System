
"""Inspect Dormora's existing registration-related PostgreSQL tables.

Backend File 11 — destination: backend/app/db/schema_audit.py
Run from the backend folder: python -m app.db.schema_audit

This diagnostic reads database structure only. It does not inspect user records,
create tables, or change the schema.
"""

from sqlalchemy import inspect
from sqlalchemy.engine import Engine
from sqlalchemy.exc import SQLAlchemyError

from app.db.database import engine


SCHEMA = "public"
TABLES = (
    "users",
    "user_profiles",
    "renter_preferences",
    "property_owner_details",
)


def show_table_schema(db_engine: Engine, table_name: str) -> None:
    """Print columns and constraints for one existing PostgreSQL table."""
    inspector = inspect(db_engine)

    print(f"\n{'=' * 68}")
    print(f"TABLE: {SCHEMA}.{table_name}")
    print("=" * 68)

    if not inspector.has_table(table_name, schema=SCHEMA):
        print("NOT FOUND — check the name in pgAdmin before continuing.")
        return

    print("\nCOLUMNS:")
    for column in inspector.get_columns(table_name, schema=SCHEMA):
        name = column["name"]
        data_type = str(column["type"])
        nullable = column.get("nullable", True)
        default = column.get("default")
        generated = bool(column.get("identity") or column.get("computed"))
        required = not nullable and default is None and not generated

        properties = ["NULL allowed" if nullable else "NOT NULL"]
        if default is not None:
            properties.append(f"default={default}")
        if generated:
            properties.append("generated by database")
        if required:
            properties.append("REQUIRED on INSERT")

        print(f"  {name}: {data_type}  |  {', '.join(properties)}")

    primary_key = inspector.get_pk_constraint(table_name, schema=SCHEMA)
    print("\nPRIMARY KEY:")
    print("  " + ", ".join(primary_key.get("constrained_columns") or ["None"]))

    print("\nUNIQUE CONSTRAINTS:")
    unique_constraints = inspector.get_unique_constraints(table_name, schema=SCHEMA)
    if not unique_constraints:
        print("  None reported")
    for constraint in unique_constraints:
        print(f"  {constraint['name']}: {', '.join(constraint['column_names'])}")

    print("\nUNIQUE INDEXES:")
    unique_indexes = [
        index
        for index in inspector.get_indexes(table_name, schema=SCHEMA)
        if index.get("unique")
    ]
    if not unique_indexes:
        print("  None reported separately")
    for index in unique_indexes:
        columns = ", ".join(
            str(name or "<expression>")
            for name in (index.get("column_names") or [])
        )
        print(f"  {index['name']}: {columns}")

    print("\nCHECK CONSTRAINTS:")
    check_constraints = inspector.get_check_constraints(table_name, schema=SCHEMA)
    if not check_constraints:
        print("  None reported")
    for constraint in check_constraints:
        print(f"  {constraint.get('name', '(unnamed)')}: {constraint['sqltext']}")

    print("\nFOREIGN KEYS:")
    foreign_keys = inspector.get_foreign_keys(table_name, schema=SCHEMA)
    if not foreign_keys:
        print("  None reported")
    for foreign_key in foreign_keys:
        local_columns = ", ".join(foreign_key.get("constrained_columns") or [])
        referenced_table = foreign_key.get("referred_table", "?")
        referenced_columns = ", ".join(foreign_key.get("referred_columns") or [])
        print(f"  {local_columns} -> {referenced_table}({referenced_columns})")


def main() -> None:
    """Inspect only table definitions, never user data or credentials."""
    try:
        with engine.connect() as connection:
            database_name = connection.exec_driver_sql(
                "SELECT current_database()"
            ).scalar_one()

        print("DORMORA REGISTRATION SCHEMA AUDIT")
        print(f"Connected database: {database_name}")
        print("Read-only inspection: no database records are displayed.")
        for table_name in TABLES:
            show_table_schema(engine, table_name)
        print("\nSchema inspection complete.")
    except SQLAlchemyError:
        print("Database schema inspection failed. Check PostgreSQL and backend/.env.")
        raise SystemExit(1) from None


if __name__ == "__main__":
    main()
