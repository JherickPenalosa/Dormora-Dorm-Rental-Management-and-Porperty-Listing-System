
BEGIN;

DO $$
BEGIN
    IF current_database() <> 'dormora_db' THEN
        RAISE EXCEPTION 'Connect to dormora_db before running File 5.';
    END IF;

    IF to_regclass('public.users') IS NULL THEN
        RAISE EXCEPTION 'Existing users table was not found.';
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.dorm_properties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    owner_user_id BIGINT NOT NULL
        REFERENCES public.users(user_id),

    name VARCHAR(120) NOT NULL,
    address VARCHAR(250) NOT NULL,
    description VARCHAR(1500) NOT NULL,

    monthly_rent NUMERIC(12, 2) NOT NULL,
    total_rooms INTEGER NOT NULL,
    available_rooms INTEGER NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'draft',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT dorm_property_name_check
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT dorm_property_address_check
        CHECK (LENGTH(TRIM(address)) > 0),

    CONSTRAINT dorm_property_rent_check
        CHECK (monthly_rent > 0),

    CONSTRAINT dorm_property_total_rooms_check
        CHECK (total_rooms >= 1),

    CONSTRAINT dorm_property_available_rooms_check
        CHECK (
            available_rooms >= 0
            AND available_rooms <= total_rooms
        ),

    CONSTRAINT dorm_property_status_check
        CHECK (
            status IN ('draft', 'published', 'archived')
        )
);

CREATE TABLE IF NOT EXISTS public.dorm_property_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    property_id BIGINT NOT NULL
        REFERENCES public.dorm_properties(id)
        ON DELETE CASCADE,

    storage_key VARCHAR(255) NOT NULL UNIQUE,
    mime_type VARCHAR(30) NOT NULL,
    byte_size INTEGER NOT NULL,
    sort_order SMALLINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT dorm_photo_type_check
        CHECK (
            mime_type IN (
                'image/jpeg',
                'image/png',
                'image/webp'
            )
        ),

    CONSTRAINT dorm_photo_size_check
        CHECK (
            byte_size > 0
            AND byte_size <= 5242880
        ),

    CONSTRAINT dorm_photo_order_check
        CHECK (sort_order BETWEEN 1 AND 8),

    CONSTRAINT dorm_photo_position_unique
        UNIQUE (property_id, sort_order)
);

CREATE INDEX IF NOT EXISTS idx_dorm_properties_owner
    ON public.dorm_properties(owner_user_id, status);

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.dorm_properties,
   public.dorm_property_photos
TO dormora_runtime;

COMMIT;

SELECT
    to_regclass('public.dorm_properties')
        AS property_table,
    to_regclass('public.dorm_property_photos')
        AS photos_table;
