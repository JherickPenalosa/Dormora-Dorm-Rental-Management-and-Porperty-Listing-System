
-- DORMORA - SYSTEM FUNCTIONALITY FILE 19
-- CREATE: backend/sql/functionality_file_19_rental_inquiries.sql
-- Execute in pgAdmin Query Tool with dormora_db selected.
-- Re-runnable: does not delete or overwrite existing records.
-- A rental inquiry is NOT a room reservation, tenancy or payment.

BEGIN;

CREATE TABLE IF NOT EXISTS public.dorm_rental_inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    property_id BIGINT NOT NULL
        REFERENCES public.dorm_properties(id) ON DELETE CASCADE,

    renter_user_id BIGINT NOT NULL
        REFERENCES public.users(user_id) ON DELETE CASCADE,

    message VARCHAR(1000),

    preferred_move_in_date DATE,

    status VARCHAR(16) NOT NULL DEFAULT 'pending',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,

    CONSTRAINT dorm_inquiry_status_check CHECK (
        status IN ('pending', 'accepted', 'rejected', 'withdrawn')
    ),

    CONSTRAINT dorm_inquiry_message_check CHECK (
        message IS NULL OR LENGTH(BTRIM(message)) > 0
    )
);

-- Only one pending inquiry per renter/property.
CREATE UNIQUE INDEX IF NOT EXISTS
    uq_dorm_rental_inquiries_pending
    ON public.dorm_rental_inquiries (property_id, renter_user_id)
    WHERE status = 'pending';

-- Fast lookup for a property owner's incoming inquiries.
CREATE INDEX IF NOT EXISTS
    idx_dorm_rental_inquiries_property_status
    ON public.dorm_rental_inquiries
    (property_id, status, created_at DESC);

-- Fast lookup for a renter's inquiry history.
CREATE INDEX IF NOT EXISTS
    idx_dorm_rental_inquiries_renter
    ON public.dorm_rental_inquiries
    (renter_user_id, created_at DESC);

-- Restricted application role permissions.
-- DELETE is deliberately not granted here.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname = 'dormora_runtime'
    ) THEN
        GRANT SELECT, INSERT, UPDATE
            ON TABLE public.dorm_rental_inquiries
            TO dormora_runtime;
    END IF;
END
$$;

COMMIT;

-- Verification: table should exist, starting at 0 inquiries.
SELECT
    to_regclass('public.dorm_rental_inquiries') AS inquiries_table,
    (SELECT COUNT(*) FROM public.dorm_rental_inquiries)
        AS inquiry_count;
